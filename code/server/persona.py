# ============================================================
#  自检：防止单反斜杠被 Python 转义吃掉（静默损坏，极难发现）
#
#  踩过的坑：上面写 `\toprule`，Python 把 `\t` 当成制表符 →
#  模型收到的是 `⇥oprule`；`\bottomrule` 的 `\b` 是退格符 → `⌫ottomrule`。
#  更阴的是 `\node` 会变成换行、`\small` 只是发个警告但原文保留。
#  这种损坏不会报错、不会崩，只会让模型读到垃圾还照着做。
#
#  所以这里直接把它变成启动即报错 —— 宁可炸得响，也不要带着坏提示词跑。
# ============================================================
def _assert_no_escape_damage() -> None:
    """扫「提示词正文」里有没有「单反斜杠 + 字母」的写法，发现就报错。

    为什么扫源文件而不是扫运行时字符串：
      运行时字符串里本来就有换行，没法用"有没有控制字符"判断 ——
      制表符和换行在多行文案里都是合法的排版字符。
      （第一版自检因为排除了制表符，漏掉了 \\toprule 变制表符这种情况。）
      而提示词正文里正确的写法一律是双反斜杠，出现单反斜杠必然是写错了。

    为什么只扫 PERSONA/OUTPUT_RULES 那一段：
      检查函数自己的代码和注释里就有正当的单反斜杠
      （`count("\\n")` 是语法、注释里举反例也要写单反斜杠）。
      第一版扫全文，结果把自己抓了，服务直接起不来。
    """
    import re as _re
    from pathlib import Path as _Path

    src = _Path(__file__).read_text(encoding="utf-8")
    try:
        start = src.index('PERSONA = """')
        end = src.index("# ============================================================")
    except ValueError:
        return

    region = src[start:end]
    offenders = []
    for m in _re.finditer(r"(?<!\\)\\[A-Za-z]", region):
        line_no = src[: start + m.start()].count("\n") + 1
        offenders.append(f"第 {line_no} 行 {m.group(0)!r}")

    if offenders:
        raise ValueError(
            "persona.py 的提示词正文里有「单反斜杠 + 字母」，会被 Python 转义吃掉"
            "（反斜杠+t 变制表符、反斜杠+b 变退格符、反斜杠+n 变换行），"
            "模型就会收到损坏的 LaTeX 命令。提示词里的反斜杠必须写成两个。\n"
            "问题位置：" + "；".join(offenders[:12])
        )


_assert_no_escape_damage()
